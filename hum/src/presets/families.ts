/**
 * Look families: the library's design system.
 *
 * A family is one look concept (usually one scene). Its takes are the variants: the same picture in
 * another palette, mood or setting (Willow by day and by moonlight). The library shows one card per
 * family, the Inspector shows the takes, and the planner and the AI director pick a family for each
 * part of the song first and a take second.
 *
 * Each family carries hand-judged fit (types in core/types.ts → LookFit):
 *   roles    the parts of a song it serves best, best first (intro, verse, build, peak = chorus/drop,
 *            break = breakdown, bridge, outro)
 *   energy   the energy range it feels right at, 0 still … 1 flat out (a take's own tags shift it a
 *            little within the family, so a calm take sits lower than a loud one)
 *   motion   how it moves most of the time: still, drifting, pulsing or explosive
 *   themes   what it is of, for the library's Theme filter (one or two)
 *   pairs    families it sits well next to; clashes: families it fights with (both work both ways,
 *            so each pair only needs writing once)
 *
 * Adding a look:
 *   - a new take of an existing family: add its id to that family's `takes` below (with a short name),
 *     or put `family: '<family id>', variant: '<take name>'` on the preset itself;
 *   - a new family: add an entry here, keyed by a new id (a one-take family can use the look's id);
 *   - neither: the look is a family of its own, with fit inferred from its tags (presets/fit.ts).
 *     A preset may also carry its own `fit` to fill in only what the inference gets wrong.
 *
 * Built-in look ids never change (saved plans, taste memory and custom looks refer to them); families
 * group them without renaming anything.
 *
 * Judgement calls: Tunnel Vision / Terminal, Marble Dream / Kaleido Candy and Neurones / Herbarium share
 * an engine but read as different pictures with different feelings (an ASCII terminal isn't a neon
 * tunnel; a kaleidoscope isn't a marble; a botanical drawing isn't a neon organism), so they stay apart.
 */
